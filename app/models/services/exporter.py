import json
import pandas as pd
from typing import Any
from app.models.topic_result import TopicResult

class Exporter:
    """Export results to CSV, JSON, and academic methodology reports."""

    def to_csv(self, result: TopicResult, output_path: str) -> str:
        """Export topics to CSV."""
        topics_df = pd.DataFrame([
            {"topic": i, **topic_weights}
            for i, topic_weights in enumerate(result.topics)
        ])
        topics_df.to_csv(output_path, index=False)
        return output_path

    def to_json(self, result: TopicResult, output_path: str) -> str:
        """Export full result to JSON."""
        # Handle TopicResult dataclass serialization
        data = {
            "model_info": result.model_info,
            "topics": result.topics,
            "doc_topics": result.doc_topics
        }
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=4)
        return output_path

    def generate_methodology_report(self, result: TopicResult, output_path: str) -> str:
        """
        Generate a Markdown report for academic reproducibility.
        """
        info = result.model_info

        report = [
            "# Topic Modelling Methodology Report",
            "",
            "## Model Configuration",
            f"- **Algorithm:** {info.get('algorithm', 'Unknown')}",
            f"- **Version:** {info.get('version', 'Unknown')}",
            f"- **Parameters:** {info.get('params', 'Not provided')}",
            "",
            "## Dataset Summary",
            f"- **Total Documents:** {info.get('num_documents', 'Unknown')}",
            f"- **Total Topics Identified:** {info.get('num_topics', 'Unknown')}",
            "",
            "## Reproducibility Notes",
            "This report was automatically generated by Project Stella. "
            "To reproduce these results, use the same input dataset and "
            "hyperparameters listed above with the specified algorithm version."
        ]

        with open(output_path, 'w', encoding='utf-8') as f:
            f.write("\n".join(report))

        return output_path
